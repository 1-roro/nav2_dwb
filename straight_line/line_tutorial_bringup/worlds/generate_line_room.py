#!/usr/bin/env python3
"""
튜토리얼용 월드 'line_room' 생성기.

Gazebo world(worlds/line_room.world)와 Nav2 맵(maps/line_room.pgm/.yaml)을 같은 기하
정의에서 만들어 둘이 어긋나지 않게 한다. 생성된 파일은 저장소에 같이 올려 두었으므로,
기하를 바꿀 때만 다시 실행하면 된다.

  python3 generate_line_room.py

turtlebot3_world 대신 이 방을 쓰는 이유:
  turtlebot3_world 는 기둥 간격이 1.1m 라 통로의 좌우 여유가 10cm 남짓이다.
  lookahead 0.6m 짜리 pure pursuit 가 회전 직후 그리는 작은 호만으로도 기둥에 닿아서,
  '제어 법칙의 결함'과 '맵이 좁아서 생긴 충돌'이 섞여 버린다.

line_tutorial_sim/kinematic_sim.hpp 의 lineRoomBlocked() 도 같은 값을 쓴다. 바꾸면 같이 고칠 것.
"""

import math
import os

HALF = 3.0            # 방 안쪽 반폭 [m] (안쪽 6m x 6m)
WALL = 0.1            # 벽 두께 [m]
HEIGHT = 0.5          # 벽/기둥 높이 [m] (waffle 의 LDS 높이보다 높게)
PILLAR = (-0.5, 0.0, 0.15)      # S3 용 기둥 (x, y, 반지름)
BOX = (-2.2, 2.2, 0.2)          # AMCL 이 방향을 헷갈리지 않게 하는 비대칭 박스 (x, y, 반폭)

RES = 0.05
MAP_HALF = HALF + WALL + 0.4    # 맵 범위 (벽 바깥 조금 포함)

HERE = os.path.dirname(os.path.abspath(__file__))


def occupied(x, y):
    if math.hypot(x - PILLAR[0], y - PILLAR[1]) <= PILLAR[2]:
        return True
    if abs(x - BOX[0]) <= BOX[2] and abs(y - BOX[1]) <= BOX[2]:
        return True
    inside_outer = abs(x) <= HALF + WALL and abs(y) <= HALF + WALL
    inside_inner = abs(x) < HALF and abs(y) < HALF
    return inside_outer and not inside_inner


def write_map():
    n = int(round(2 * MAP_HALF / RES))
    rows = []
    for r in range(n):
        y = MAP_HALF - (r + 0.5) * RES          # pgm 의 첫 줄이 맵의 위쪽(+y)
        row = bytearray()
        for c in range(n):
            x = -MAP_HALF + (c + 0.5) * RES
            if occupied(x, y):
                row.append(0)                     # 검정 = 점유
            elif abs(x) > HALF + WALL or abs(y) > HALF + WALL:
                row.append(205)                   # 벽 바깥 = 미지
            else:
                row.append(254)                   # 흰색 = 빈 공간
        rows.append(bytes(row))
    maps = os.path.join(HERE, '..', 'maps')
    os.makedirs(maps, exist_ok=True)
    with open(os.path.join(maps, 'line_room.pgm'), 'wb') as f:
        f.write(b'P5\n%d %d\n255\n' % (n, n))
        f.write(b''.join(rows))
    with open(os.path.join(maps, 'line_room.yaml'), 'w') as f:
        f.write('image: line_room.pgm\n'
                'mode: trinary\n'
                f'resolution: {RES}\n'
                f'origin: [{-MAP_HALF}, {-MAP_HALF}, 0.0]\n'
                'negate: 0\n'
                'occupied_thresh: 0.65\n'
                'free_thresh: 0.25\n')


def box_link(name, x, y, sx, sy):
    return f"""
      <link name="{name}">
        <pose>{x} {y} {HEIGHT / 2} 0 0 0</pose>
        <collision name="collision">
          <geometry><box><size>{sx} {sy} {HEIGHT}</size></box></geometry>
        </collision>
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {HEIGHT}</size></box></geometry>
          <material>
            <script>
              <uri>file://media/materials/scripts/gazebo.material</uri>
              <name>Gazebo/Grey</name>
            </script>
          </material>
        </visual>
      </link>"""


def write_world():
    c = HALF + WALL / 2
    length = 2 * (HALF + WALL)
    walls = (box_link('north', 0, c, length, WALL) + box_link('south', 0, -c, length, WALL) +
             box_link('east', c, 0, WALL, length) + box_link('west', -c, 0, WALL, length))
    px, py, pr = PILLAR
    bx, by, bh = BOX
    world = f"""<?xml version="1.0"?>
<!-- generated by generate_line_room.py; edit the generator, not this file -->
<sdf version="1.6">
  <world name="default">

    <include>
      <uri>model://ground_plane</uri>
    </include>

    <include>
      <uri>model://sun</uri>
    </include>

    <scene>
      <shadows>false</shadows>
    </scene>

    <gui fullscreen='0'>
      <camera name='user_camera'>
        <pose frame=''>0 0 12 0 1.570796 0</pose>
        <view_controller>orbit</view_controller>
        <projection_type>perspective</projection_type>
      </camera>
    </gui>

    <physics type="ode">
      <real_time_update_rate>1000.0</real_time_update_rate>
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
    </physics>

    <model name="walls">
      <static>true</static>{walls}
    </model>

    <model name="pillar">
      <static>true</static>
      <pose>{px} {py} {HEIGHT / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><cylinder><radius>{pr}</radius><length>{HEIGHT}</length></cylinder></geometry>
        </collision>
        <visual name="visual">
          <geometry><cylinder><radius>{pr}</radius><length>{HEIGHT}</length></cylinder></geometry>
          <material>
            <script>
              <uri>file://media/materials/scripts/gazebo.material</uri>
              <name>Gazebo/Red</name>
            </script>
          </material>
        </visual>
      </link>
    </model>

    <model name="marker_box">
      <static>true</static>{box_link('link', bx, by, 2 * bh, 2 * bh)}
    </model>

  </world>
</sdf>
"""
    with open(os.path.join(HERE, 'line_room.world'), 'w') as f:
        f.write(world)


if __name__ == '__main__':
    write_map()
    write_world()
    print('wrote worlds/line_room.world, maps/line_room.pgm, maps/line_room.yaml')
